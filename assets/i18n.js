const languageStorageKey = "dfw-portfolio-language";
let savedLanguage;
try {
  savedLanguage = localStorage.getItem(languageStorageKey);
} catch {
  // Language switching also works when browser storage is unavailable.
}
let currentLanguage = ["es", "en"].includes(savedLanguage)
  ? savedLanguage
  : (navigator.language.toLowerCase().startsWith("es") ? "es" : "en");

function t(source) {
  return currentLanguage === "es" ? (spanishTranslations[source] ?? source) : source;
}

function translateElements(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    const source = element.dataset.i18n || element.textContent.trim().replace(/\s+/g, " ");
    element.dataset.i18n = source;
    element.textContent = t(source);
  });
  ["aria-label", "alt"].forEach((attribute) => {
    root.querySelectorAll(`[data-i18n-${attribute}]`).forEach((element) => {
      element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
    });
  });
}
